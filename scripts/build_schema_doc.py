def main() -> int:
    connection = duckdb.connect()
    sections = [HEADER]
    problems = []
    for table, notes in NOTES.items():
        path = (SAMPLE_DIR / f"{table}.parquet").as_posix()
        names = [row[0] for row in connection.sql(f"DESCRIBE SELECT * FROM read_parquet('{path}')").fetchall()]
        problems += [f"{table}.{c}: missing from NOTES" for c in names if c not in notes]
        problems += [f"{table}.{c}: in NOTES but not in the table" for c in notes if c not in names]
        noted = "; ".join(f"{c}: {notes[c]}" for c in names if notes.get(c))
        sections.append(
            f"## NFLVERSE.{table} ({TABLE_NOTES[table]})\n"
            f"Columns: {', '.join(names)}\n"
            + (f"Notes: {noted}\n" if noted else "")
        )
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    OUTPUT.write_text("\n".join(sections), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
